# Allow inbound to the Docker-host's mapped container SSH ports (2200-2300)
# and all PE service ports so agents and the console can reach the primary
# directly (no tunnel needed).
resource "google_compute_firewall" "dockerhost" {
  count       = var.docker_host_count
  name        = "${var.prefix}-dockerhost"
  network     = "default"
  allow {
    protocol = "tcp"
    ports    = ["2200-2300", "80", "443", "4430", "4431", "4432", "4433", "5432", "5525", "8080", "8081", "8140", "8142", "8143", "8147", "8170"]
  }
  source_ranges = [local.internal_range]
  target_tags   = ["pe-lab-dockerhost"]
}

# Open hieranano (5525) on the VM-topology nodes (pe-lab tag).  INTERNAL-ONLY:
# external ingress is SSH-only, so nothing outside the VPC can reach it.
resource "google_compute_firewall" "hieranano" {
  count       = 1
  name        = "${var.prefix}-hieranano"
  network     = "default"
  allow {
    protocol = "tcp"
    ports    = ["5525"]
  }
  source_ranges = [local.internal_range]
  target_tags   = ["pe-lab"]
}

# SECURITY: INTERNAL ingress – allow EVERYTHING from the VPC subnet.  Any VM
# inside the network (jump host, the Docker host itself, VM nodes) can reach
# every port on the lab VMs.
resource "google_compute_firewall" "internal" {
  count         = 1
  name          = "${var.prefix}-internal"
  network       = "default"
  source_ranges = [local.internal_range]
  target_tags   = ["pe-lab", "pe-lab-dockerhost"]
  allow {
    protocol = "tcp"
  }
  allow {
    protocol = "udp"
  }
  allow {
    protocol = "icmp"
  }
}

# SECURITY: EXTERNAL ingress – SSH ONLY.  Everything else (console/HTTP(S),
# PE services 8140/4433/…, mapped container SSH 2200-2300, databases, …) is
# reachable from INSIDE the VPC only: use an internal VM (jump host) for all
# of it.  The VMs do NOT carry the http-server/https-server tags, so no
# project-default rule opens 80/443 externally either.
resource "google_compute_firewall" "external" {
  count         = 1
  name          = "${var.prefix}-external"
  network       = "default"
  source_ranges = ["0.0.0.0/0"]
  target_tags   = ["pe-lab", "pe-lab-dockerhost"]
  allow {
    protocol = "tcp"
    ports    = ["22"]
  }
}

output "dockerhost_ip" {
  # Internal (private) network IP, not the ephemeral public NAT IP.  The internal
  # address is stable across VM restarts and is present even in air-gapped
  # environments where no external interface exists.  The wizard host must be on
  # the same internal network to reach it (internal-to-internal only).
  value = var.docker_host_count == 1 ? google_compute_instance.dockerhost[0].network_interface[0].network_ip : ""
}
EOMAINTF

  cat > "${tf_dir}/variables.tf" <<'EOVARS'
variable "gcp_project" {
  type = string
}

variable "region" {
  type = string
}

variable "zone" {
  type = string
}

variable "prefix" {
  type = string
}

variable "node_count" {
  type = number
}

variable "compiler_count" {
  type    = number
  default = 0
}

variable "haproxy_count" {
  type    = number
  default = 0
}

variable "docker_host_count" {
  type    = number
  default = 0
}

variable "docker_host_ip" {
  type    = string
  default = ""   # blank = auto-assigned (ephemeral internal IP, works in any subnet)
}

variable "test_count" {
  type    = number
  default = 1
}

variable "infra_type" {
  type = string
}

variable "compiler_type" {
  type = string
}

variable "custom_image" {
  type = string
}

variable "ssh_user" {
  type    = string
  default = "root"
}

variable "ssh_public_key" {
  type = string
}

variable "preemptible" {
  type    = bool
  default = false
}

variable "internal_source_range" {
  type    = string
  default = ""   # blank = auto (the VPC subnet CIDR for the region)
}
EOVARS

  local pub_key_content
  pub_key_content=$(cat "${ssh_key_path}.pub")

  local docker_host_count=0
  if [[ "$runtime" == "docker" && "$docker_host" == "cloud" ]]; then
    docker_host_count=1
  fi

  # A plain test node (no PE/agent) is always provisioned for VM runs.  For
  # docker+cloud the test node is a container on the Docker host, so no VM.
  local tf_test_count=1
  if [[ "$runtime" == "docker" && "$docker_host" == "cloud" ]]; then
    tf_test_count=0
  fi

  # For docker+cloud only the Docker-host VM is provisioned – the PE nodes are
  # containers on it, so no core/compiler/haproxy VMs are created.
  local tf_node_count=$node_count
  local tf_compiler_count=$compiler_count
  local tf_haproxy_count=$haproxy_count
  if [[ "$runtime" == "docker" && "$docker_host" == "cloud" ]]; then
    tf_node_count=0; tf_compiler_count=0; tf_haproxy_count=0
  fi

  cat > "${tf_dir}/terraform.tfvars" <<EOTFVARS
gcp_project    = "${gcp_project}"
region         = "${region}"
zone           = "${full_zone}"
prefix         = "${nodeprefix}"
node_count     = ${tf_node_count}
compiler_count = ${tf_compiler_count}
haproxy_count  = ${tf_haproxy_count}
docker_host_count = ${docker_host_count}
docker_host_ip    = "${docker_host_static_ip}"
test_count       = ${tf_test_count}
infra_type     = "${gcp_machine_type}"
compiler_type  = "${gcp_compiler_type}"
custom_image   = "${custom_image}"
ssh_user       = "${ssh_user}"
ssh_public_key = "${pub_key_content}"
preemptible    = false
EOTFVARS

  tui_ok "Terraform written to ${tf_dir}/"
  tf_dir_active="$tf_dir"
}

