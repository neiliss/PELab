generate_terraform_gcp() {
  # Isolate Terraform state PER prefix so a NEW build can never destroy a prior
  # build.  Each nodeprefix gets its own <prefix>/ subdir with its own
  # terraform.tfstate; switching prefixes (or deleting one build) only affects
  # that build.  PE_TF_DIR overrides (e.g. swing) are honoured as-is.
  local tf_dir="${PE_TF_DIR:-${script_dir}/terraform/gcp/${nodeprefix}}"
  mkdir -p "$tf_dir"

  cat > "${tf_dir}/main.tf" <<'EOMAINTF'
# ============================================================
# PE Lab – GCP Terraform configuration
# Generated by setup_wizard.sh
# ============================================================
terraform {
  required_version = ">= 1.3.0"
  required_providers {
    google = {
      source  = "hashicorp/google"
      version = "~> 5.0"
    }
  }
}

provider "google" {
  project = var.gcp_project
  region  = var.region
  zone    = var.zone
}

# The VPC ("default" network) subnet for the chosen region.  Its CIDR is the
# "internal" source range: everything INSIDE the VPC may reach every port on
# the lab VMs, while external ingress is limited to SSH/HTTP/HTTPS only.
data "google_compute_subnetwork" "default" {
  name   = "default"
  region = var.region
}

# Labels applied to every provisioned VM so instances can be attributed to
# their owner (visible in the GCP console and via `gcloud --filter labels.owner`).
locals {
  vm_labels = {
    owner = "lab"
  }
  # Internal source range: the VPC subnet CIDR (overridable via tfvars).
  internal_range = var.internal_source_range != "" ? var.internal_source_range : data.google_compute_subnetwork.default.ip_cidr_range
}

resource "google_compute_instance" "core" {
  count        = var.node_count
  name         = "${var.prefix}core${count.index}"
  machine_type = var.infra_type
  labels       = local.vm_labels
  zone         = var.zone

  scheduling {
    preemptible = var.preemptible
  }

  boot_disk {
    initialize_params {
      image = var.custom_image
    }
  }

  network_interface {
    network = "default"
    access_config {}
  }

  metadata = {
    ssh-keys = "${var.ssh_user}:${var.ssh_public_key}"
  }

  tags = ["pe-lab"]
}

