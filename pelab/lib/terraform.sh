# Single Docker-host VM (used when docker_host=cloud).  All PE containers run on
# this VM; each container's SSH (22) is mapped to a unique host port (2201+).
resource "google_compute_instance" "dockerhost" {
  count        = var.docker_host_count
  name         = "${var.prefix}dockerhost"
  machine_type = var.infra_type
  labels       = local.vm_labels
  zone         = var.zone

  scheduling {
    preemptible = var.preemptible
  }

  boot_disk {
    initialize_params {
      image = var.custom_image
    }
  }

  network_interface {
    network    = "default"
    # Optional static internal IP for the Docker-host VM (blank = ephemeral).
    # Pinning it keeps the internal address stable across rebuilds; when empty
    # GCP auto-assigns, which works for any subnet/region.
    network_ip = var.docker_host_ip != "" ? var.docker_host_ip : null
    access_config {}
  }

  metadata = {
    ssh-keys = "${var.ssh_user}:${var.ssh_public_key}"
  }

  tags = ["pe-lab", "pe-lab-dockerhost"]
}

